#!/usr/bin/env python3
"""Generate Mxplorer's icon bitmaps from Google's Material Symbols Rounded.

Usage:
    gen_icons.py <MaterialSymbolsRounded[...].ttf> <.codepoints> <out.c>

The variable font and its .codepoints file come from
https://github.com/google/material-design-icons (variablefont/), Apache 2.0.
Each icon is stored as an 8-bit coverage mask at every size listed in SIZES;
icons in BIG are also stored at 48 px. Needs Pillow with FreeType.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ICONS = [
    "arrow_back", "arrow_forward", "refresh", "close", "home", "settings",
    "dark_mode", "light_mode", "code", "more_vert", "search", "lock",
    "lock_open", "info", "public", "add", "tune", "palette", "shield",
    "javascript", "terminal", "account_tree", "swap_vert", "description",
    "speed", "block", "chevron_right", "expand_more", "warning", "error",
    "check_circle", "arrow_right", "arrow_drop_down", "arrow_selector_tool",
    "wifi_off", "cloud_off", "image", "broken_image", "travel_explore",
    "bug_report", "check_box", "check_box_outline_blank",
    "radio_button_checked", "radio_button_unchecked", "check", "open_in_new",
    "web", "keyboard_arrow_right", "filter_list", "content_copy", "language",
    "history", "star", "bolt", "drag_handle", "unfold_more", "visibility",
    "download", "link", "computer", "dns", "html", "css", "data_object",
    "schedule", "memory", "timer", "play_arrow", "pause", "delete",
]
BIG = ["wifi_off", "cloud_off", "error", "lock", "travel_explore", "public",
       "bug_report", "javascript", "broken_image", "code", "palette", "web"]
SIZES = [16, 20]


def axes_for(font, size, fill):
    names = [a["name"] if isinstance(a["name"], str) else a["name"].decode()
             for a in font.get_variation_axes()]
    values = []
    for name in names:
        key = name.lower()
        if key.startswith("fill"):
            values.append(fill)
        elif key.startswith("grad"):
            values.append(0)
        elif key.startswith("optical") or key.startswith("opsz"):
            values.append(max(20, min(48, size)))
        elif key.startswith("weight") or key.startswith("wght"):
            values.append(400)
        else:
            values.append(0)
    font.set_variation_by_axes(values)


def render(path, codepoint, size, fill):
    font = ImageFont.truetype(path, size)
    axes_for(font, size, fill)
    image = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(image)
    # The icon's em square fills the image; its baseline is the bottom edge.
    draw.text((0, size), chr(codepoint), fill=255, font=font, anchor="ls")
    return image.tobytes()


def main():
    font_path, codepoint_path, out_path = sys.argv[1:4]
    codepoints = {}
    for line in open(codepoint_path):
        parts = line.split()
        if len(parts) == 2:
            codepoints[parts[0]] = int(parts[1], 16)
    missing = [name for name in ICONS + BIG if name not in codepoints]
    if missing:
        sys.exit("missing icons: " + ", ".join(missing))
    for name in BIG:
        if name not in ICONS:
            ICONS.append(name)

    out = []
    out.append("/* Generated by tools/gen_icons.py from Google's Material Symbols")
    out.append(" * Rounded (Apache License 2.0). Do not edit by hand. */")
    out.append('#include "mxplorer/gfx.h"\n')
    entries = []
    for name in ICONS:
        sizes = SIZES + ([48] if name in BIG else [])
        for size in sizes:
            data = render(font_path, codepoints[name], size, 0)
            symbol = "icon_%s_%d" % (name, size)
            out.append("static const unsigned char %s[%d] = {" % (symbol, len(data)))
            for i in range(0, len(data), 24):
                out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
            out.append("};")
            entries.append((name, size, symbol))
    out.append("\nconst mx_icon_bitmap_t mx_icon_bitmaps[] = {")
    for name, size, symbol in entries:
        out.append("    {MX_ICON_%s, %d, %s}," % (name.upper(), size, symbol))
    out.append("};")
    out.append("const unsigned mx_icon_bitmap_count = %d;" % len(entries))
    open(out_path, "w").write("\n".join(out) + "\n")

    header = ["/* Generated by tools/gen_icons.py. Do not edit by hand. */",
              "#ifndef MXPLORER_ICON_IDS_H", "#define MXPLORER_ICON_IDS_H", "",
              "typedef enum {"]
    for name in ICONS:
        header.append("    MX_ICON_%s," % name.upper())
    header += ["    MX_ICON_COUNT", "} mx_icon_t;", "", "#endif", ""]
    import os
    header_path = os.path.join(os.path.dirname(os.path.abspath(out_path)),
                               "include", "mxplorer", "icon_ids.h")
    open(header_path, "w").write("\n".join(header))

    # Contact sheet for checking the result by eye.
    sheet = Image.new("L", (len(ICONS) * 52, 52 * 3), 255)
    for i, name in enumerate(ICONS):
        for row, size in enumerate([16, 20, 48]):
            if size == 48 and name not in BIG:
                continue
            mask = Image.frombytes("L", (size, size),
                                   render(font_path, codepoints[name], size, 0))
            sheet.paste(0, (i * 52 + 2, row * 52 + 2), mask)
    sheet.save(out_path + ".sheet.png")


if __name__ == "__main__":
    main()
