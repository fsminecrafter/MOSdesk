#!/usr/bin/env python3
"""Generate mosWM's panel icons (wm_panel_icons.h) from Google's Material
Symbols Rounded (Apache 2.0, github.com/google/material-design-icons).

    gen_panel_icons.py <MaterialSymbolsRounded[...].ttf> <.codepoints> <out.h>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ICONS = ["volume_up", "volume_down", "volume_mute", "volume_off", "lan",
         "settings_ethernet", "wifi", "wifi_off", "network_wifi_1_bar",
         "network_wifi_2_bar", "network_wifi_3_bar", "signal_wifi_off",
         "cable", "check", "language", "router", "dns"]
SIZES = [20, 24]


def render(path, cp, size):
    font = ImageFont.truetype(path, size)
    axes = []
    for a in font.get_variation_axes():
        name = a["name"] if isinstance(a["name"], str) else a["name"].decode()
        name = name.lower()
        axes.append(0 if name.startswith(("fill", "grad")) else
                    max(20, min(48, size)) if name.startswith(("opt", "opsz")) else
                    400 if name.startswith(("weight", "wght")) else 0)
    font.set_variation_by_axes(axes)
    img = Image.new("L", (size, size), 0)
    ImageDraw.Draw(img).text((0, size), chr(cp), fill=255, font=font, anchor="ls")
    return img.tobytes()


def main():
    font, cps_path, out = sys.argv[1:4]
    cps = dict(l.split() for l in open(cps_path) if len(l.split()) == 2)
    lines = ["/* Generated by tools/gen_panel_icons.py from Material Symbols Rounded",
             " * (Google, Apache License 2.0). 8-bit coverage, row major. */",
             "#ifndef WM_PANEL_ICONS_H", "#define WM_PANEL_ICONS_H", "#include <stdint.h>", ""]
    lines.append("enum {")
    for n in ICONS: lines.append("    WM_ICON_%s," % n.upper())
    lines += ["    WM_ICON_COUNT", "};", ""]
    for size in SIZES:
        for n in ICONS:
            data = render(font, int(cps[n], 16), size)
            lines.append("static const uint8_t wm_icon_%s_%d[%d] = {" % (n, size, len(data)))
            for i in range(0, len(data), 24):
                lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
            lines.append("};")
        lines.append("static const uint8_t* const wm_icons_%d[WM_ICON_COUNT] = {" % size)
        lines += ["    wm_icon_%s_%d," % (n, size) for n in ICONS]
        lines.append("};")
    lines += ["", "#endif", ""]
    open(out, "w").write("\n".join(lines))


main()
